/**
 * English / Urdu toggle. English is never stored anywhere — it's
 * whatever markup is already in the DOM, so it can't drift out of sync
 * with the page. Switching to Urdu walks every [data-i18n] element,
 * caches its current innerHTML on a data attribute the first time
 * (so switching back to English is an exact restore, not a re-render),
 * and swaps in the matching dictionary entry. innerHTML rather than
 * textContent deliberately — several headlines carry a <br> or an
 * inline <span> for the accent word, and a plain text swap would lose
 * that structure permanently on the next switch back.
 *
 * Dictionary values are the Urdu translation as HTML — most are plain
 * text, some carry the same <br>/<span> markup as their English source.
 * Exam names and institution names (MDCAT, LNAT, LUMS, NUST…) are left
 * in Latin script in both languages, same as any other proper noun.
 *
 * Initial lang/dir is set before this module loads by the inline head
 * script (see any page's <head>) so there's no flash — this module
 * wires the toggle button and performs the actual text swap.
 */
const STORAGE_KEY = "arthic-lang";

type Lang = "en" | "ur";

export function initLang(): void {
  applyToggleLabel(currentLang());

  const toggles = document.querySelectorAll<HTMLButtonElement>("[data-lang-toggle]");
  if (toggles.length === 0) return;

  toggles.forEach((toggle) => {
    toggle.addEventListener("click", () => {
      const next: Lang = currentLang() === "ur" ? "en" : "ur";
      applyLang(next);
      try {
        localStorage.setItem(STORAGE_KEY, next);
      } catch {
        /* localStorage unavailable — the switch still works for this view */
      }
    });
  });

  // The head script already set lang/dir before paint; this pass makes
  // the *text* match on first load if the saved preference was Urdu.
  if (currentLang() === "ur") applyLang("ur", { skipAttrs: true });
}

function currentLang(): Lang {
  return document.documentElement.getAttribute("lang") === "ur" ? "ur" : "en";
}

function applyLang(lang: Lang, opts: { skipAttrs?: boolean } = {}): void {
  if (!opts.skipAttrs) {
    document.documentElement.setAttribute("lang", lang === "ur" ? "ur" : "en");
    document.documentElement.setAttribute("dir", lang === "ur" ? "rtl" : "ltr");
  }

  document.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (!key) return;

    if (el.dataset.i18nEn === undefined) {
      el.dataset.i18nEn = el.innerHTML;
    }

    if (lang === "ur") {
      const translated = dictionary[key];
      el.innerHTML = translated !== undefined ? translated : el.dataset.i18nEn;
    } else {
      el.innerHTML = el.dataset.i18nEn;
    }
  });

  // A handful of attributes (placeholder text, aria-labels) carry
  // copy too — same cache-then-swap approach, just against a named
  // attribute instead of innerHTML.
  document.querySelectorAll<HTMLElement>("[data-i18n-attr]").forEach((el) => {
    const spec = el.dataset.i18nAttr;
    if (!spec) return;
    const [attr, key] = spec.split(":");
    if (!attr || !key) return;
    const cacheAttr = `data-i18n-attr-en-${attr}`;
    if (!el.hasAttribute(cacheAttr)) {
      el.setAttribute(cacheAttr, el.getAttribute(attr) ?? "");
    }
    if (lang === "ur") {
      const translated = dictionary[key];
      el.setAttribute(attr, translated !== undefined ? translated : el.getAttribute(cacheAttr) ?? "");
    } else {
      el.setAttribute(attr, el.getAttribute(cacheAttr) ?? "");
    }
  });

  applyToggleLabel(lang);
}

function applyToggleLabel(lang: Lang): void {
  document.querySelectorAll<HTMLElement>("[data-lang-toggle-label]").forEach((el) => {
    el.textContent = lang === "ur" ? "EN" : "اردو";
  });
  document.querySelectorAll<HTMLButtonElement>("[data-lang-toggle]").forEach((el) => {
    el.setAttribute("aria-label", lang === "ur" ? "switch to English" : "اردو میں دیکھیں");
  });
}

